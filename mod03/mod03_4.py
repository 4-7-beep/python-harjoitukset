Kokonaisluku_1 = input("Anna ensimmäinen kokonaisluku: " )
Kokonaisluku_2 = input("Anna toinen kokonaisluku: " )
Kokonaisluku_3 = input("Anna kolmas kokonaisluku: " )

print("Kokonaislukujen summa on: " + str(int(Kokonaisluku_1) + int(Kokonaisluku_2) + int(Kokonaisluku_3)))

print("Kokonaislukujen tulo on: " + str(int(Kokonaisluku_1) * int(Kokonaisluku_2) * int(Kokonaisluku_3)))

print("Kokonaislukujen keskiarvo on: " + str((int(Kokonaisluku_1) + int(Kokonaisluku_2) + int(Kokonaisluku_3)) / 3))