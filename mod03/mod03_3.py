Suorakulmion_kanta = input("Anna suorakulmion kannan pituus: ")
Suorakulmion_korkeus = input("Anna suorakulmion korkeus: ")

Suorakulmion_piiri = 2 * (float(Suorakulmion_kanta) + float(Suorakulmion_korkeus))
print("Suorakulmion piiri on: " + str(Suorakulmion_piiri))

Suorakulmion_pinta_ala = float(Suorakulmion_kanta) * float(Suorakulmion_korkeus)
print("Suorakulmion pinta-ala on: " + str(Suorakulmion_pinta_ala))